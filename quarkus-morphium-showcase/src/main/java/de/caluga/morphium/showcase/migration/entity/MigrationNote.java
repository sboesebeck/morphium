package de.caluga.morphium.showcase.migration.entity;

import de.caluga.morphium.annotations.CreationTime;
import de.caluga.morphium.annotations.Entity;
import de.caluga.morphium.annotations.Id;
import de.caluga.morphium.driver.MorphiumId;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.experimental.FieldNameConstants;

/**
 * A deliberately simple Morphium entity used to demonstrate quarkus-morphium's
 * <strong>Migration Runner</strong> ({@code de.caluga.morphium.quarkus.migration}).
 *
 * <p>Documents are seeded WITHOUT the {@code archived} field (an older "schema version"),
 * then {@link de.caluga.morphium.showcase.migration.AddArchivedFlagMigration} backfills
 * {@code archived = false} on every existing document that is still missing it &mdash;
 * exactly the kind of one-time, idempotent data migration
 * {@code @MorphiumChangeUnit} exists for.</p>
 *
 * @see de.caluga.morphium.showcase.migration.AddArchivedFlagMigration
 * @see de.caluga.morphium.showcase.migration.MigrationService
 */
@Entity(collectionName = "migration_notes")
@Data
@NoArgsConstructor
@AllArgsConstructor
@Builder
@FieldNameConstants
public class MigrationNote {

    /** Auto-generated by Morphium on insert when left {@code null}. */
    @Id
    private MorphiumId id;

    /** Short title, shown in the notes table. */
    private String title;

    /**
     * Deliberately left {@code null} by the seeding step to simulate documents written by an
     * older application version that did not yet have this field. The migration backfills it.
     */
    private Boolean archived;

    /** Set automatically by Morphium on the first {@code store()} call. */
    @CreationTime
    private java.time.LocalDateTime createdAt;
}
