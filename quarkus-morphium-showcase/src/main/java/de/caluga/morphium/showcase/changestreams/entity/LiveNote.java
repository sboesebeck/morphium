package de.caluga.morphium.showcase.changestreams.entity;

import de.caluga.morphium.annotations.CreationTime;
import de.caluga.morphium.annotations.Entity;
import de.caluga.morphium.annotations.Id;
import de.caluga.morphium.annotations.LastChange;
import de.caluga.morphium.driver.MorphiumId;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import lombok.experimental.FieldNameConstants;

import java.time.LocalDateTime;

/**
 * A deliberately simple Morphium entity used to demonstrate <strong>MongoDB Change Streams</strong>.
 *
 * <p>Change Streams notify listening clients in (near) realtime whenever a document in a
 * watched collection is inserted, updated, replaced, or deleted &mdash; without any polling.
 * Morphium exposes this MongoDB feature through {@link de.caluga.morphium.changestream.ChangeStreamMonitor},
 * which this showcase feature wires up for the {@code live_notes} collection.</p>
 *
 * <h3>Key Morphium Features Demonstrated by this Entity</h3>
 * <ul>
 *   <li>{@code @Entity(collectionName = "live_notes")} -- explicit collection name so the
 *       change stream can be scoped precisely to this collection.</li>
 *   <li>{@code @CreationTime} -- automatically set on first {@code store()}.</li>
 *   <li>{@code @LastChange} -- automatically updated on every subsequent {@code store()}/update,
 *       giving change-stream consumers an easy "what changed and when" signal even before
 *       inspecting the change event's {@code updateDescription}.</li>
 * </ul>
 *
 * <p>Nothing here is change-stream-specific &mdash; that is the point. Change Streams work on
 * <em>any</em> Morphium entity/collection; there is no special annotation required on the
 * entity itself. The realtime behavior is entirely configured on the watching side (see
 * {@link de.caluga.morphium.showcase.changestreams.LiveNoteChangeStreamService}).</p>
 *
 * @see de.caluga.morphium.showcase.changestreams.LiveNoteChangeStreamService
 * @see de.caluga.morphium.showcase.changestreams.LiveNoteService
 */
@Entity(collectionName = "live_notes")
@Data
@NoArgsConstructor
@AllArgsConstructor
@Builder
@FieldNameConstants
public class LiveNote {

    /**
     * The unique document identifier, mapped to MongoDB's {@code _id}.
     * Auto-generated by Morphium on insert when left {@code null}.
     */
    @Id
    private MorphiumId id;

    /** Short title of the note, shown in the live feed. */
    private String title;

    /** Free-text note content. */
    private String content;

    /** Author / owner of the note, used to illustrate filtered updates and deletes. */
    private String author;

    /**
     * Set automatically by Morphium on the first {@code store()} call. Never modified
     * afterwards -- a true "created at" timestamp.
     */
    @CreationTime
    private LocalDateTime createdAt;

    /**
     * Updated by Morphium on every subsequent {@code store()}/update call. Useful to
     * cross-check against the change stream's own {@code clusterTime}.
     */
    @LastChange
    private LocalDateTime updatedAt;
}
